export function pickExercises(
  count: number,
  equipment: Equipment[],
  bodyPart?: string,
): ExerciseTemplate[] {
  const available = exerciseLibrary.filter(
    (e) => equipment.includes('gym') || e.equipment.every((eq) => equipment.includes(eq) || eq === 'none'),
  )
  let pool = bodyPart ? available.filter((e) => e.bodyPart === bodyPart) : available
  if (pool.length === 0) pool = available
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  const result: ExerciseTemplate[] = []
  let i = 0
  while (result.length < count && pool.length > 0) {
    result.push(shuffled[i % shuffled.length])
    i++
  }
  return result
}
